def build_channel_vip_markup(bot_username: str):
    """Inline button markup linking to the bot for purchasing VIP configs."""
    markup = types.InlineKeyboardMarkup(row_width=1)
    clean_bot = (bot_username or "litixconnectBot").lstrip("@")
    markup.add(
        types.InlineKeyboardButton("💎 خرید مستقیم از ربات (تحویل آنی)", url=f"https://t.me/{clean_bot}?start=buy"),
        types.InlineKeyboardButton("🎁 باشگاه مشتریان (تخفیف تا ۳۰٪)", url=f"https://t.me/{clean_bot}?start=club"),
        types.InlineKeyboardButton("👨‍💻 پشتیبانی و مشاوره ۲۴ ساعته", url="https://t.me/awlinavakhtam")
    )
    return markup


def send_persian_announcement(bot, channel_id: str, bot_username: str, template_id: int = 1) -> bool:
    """Send a selected Persian announcement to the Telegram channel."""
    if not channel_id:
        logger.warning("CHANNEL_ID is not configured, skipping announcement post")
        return False

    tmpl = VIP_ANNOUNCEMENTS.get(template_id, VIP_ANNOUNCEMENTS[1])
    text = tmpl["text"]
    markup = build_channel_vip_markup(bot_username)

    try:
        bot.send_message(
            channel_id,
            text,
            parse_mode="HTML",
            reply_markup=markup,
            disable_web_page_preview=True
        )
        logger.info("Successfully posted Persian announcement #%d ('%s') to %s", template_id, tmpl['title'], channel_id)
        return True
    except Exception as e:
        logger.error("Failed to post Persian announcement to %s: %s", channel_id, e)
        return False


def post_full_tariffs_to_channel(bot, channel_id: str, bot_username: str = "litixconnectBot", banner_path=None) -> bool:
    """Post banner and full comprehensive tariff table to the channel with actionable buttons."""
    if not channel_id:
        logger.warning("CHANNEL_ID missing for tariff posting")
        return False

    markup = build_channel_vip_markup(bot_username)

    try:
        # If banner image exists, post it first as eye-catching cover
        if banner_path and Path(banner_path).exists():
            caption = (
                "⚡️ <b>تعرفه رسمی اشتراک‌های اختصاصی و پرسرعت VIP</b>\n"
                "🌐 <i>شبکه خروجی چندگانه اختصاصی (آمریکا، هلند و آلمان) | بدون تحریم و پینگ پایین</i>\n\n"
                "🎁 <b>همراه با تخفیف ۳۰ درصدی باشگاه مشتریان!</b>\n"
                "👇 لیست کامل پلن‌ها و قیمت‌ها در پیام زیر 👇"
            )
            with open(banner_path, "rb") as photo_file:
                bot.send_photo(channel_id, photo_file, caption=caption, parse_mode="HTML")

        # Post the full comprehensive tariff table
        bot.send_message(
            channel_id,
            TARIFF_ANNOUNCEMENT_FULL_TEXT,
            parse_mode="HTML",
            reply_markup=markup,
            disable_web_page_preview=True
        )
        logger.info("Successfully posted full tariff announcement to channel %s", channel_id)
        return True
    except Exception as e:
        logger.error("Failed to post full tariffs to channel %s: %s", channel_id, e)
        return False
